"""Writes CombiningMarks.java: the code points Python's unicodedata.combining() reports as non-zero.

Java has no API for the canonical combining class, and the Python library drops exactly these
characters after NFKD; run with the Python version the reference results come from.
"""
import sys
import unicodedata
from pathlib import Path

ranges, start = [], None
for cp in range(0x110000):
    c = unicodedata.combining(chr(cp)) != 0
    if c and start is None:
        start = cp
    if not c and start is not None:
        ranges.append((start, cp - 1))
        start = None
rows = ",\n".join("        " + ", ".join(f"0x{a:X}, 0x{b:X}" for a, b in ranges[i:i + 6]) for i in range(0, len(ranges), 6))
out = f'''package io.github.msinghal34.namematch;

/** Generated by java/tools/gen_combining.py from Unicode {unicodedata.unidata_version}; do not edit. */
final class CombiningMarks {{
    private CombiningMarks() {{
    }}

    /** Inclusive ranges of code points with a non-zero canonical combining class, sorted. */
    private static final int[] RANGES = {{
{rows}
    }};

    static boolean isCombining(int cp) {{
        int lo = 0;
        int hi = RANGES.length / 2 - 1;
        while (lo <= hi) {{
            int mid = (lo + hi) >>> 1;
            if (cp < RANGES[2 * mid]) {{
                hi = mid - 1;
            }} else if (cp > RANGES[2 * mid + 1]) {{
                lo = mid + 1;
            }} else {{
                return true;
            }}
        }}
        return false;
    }}
}}
'''
Path(sys.argv[1]).write_text(out)
